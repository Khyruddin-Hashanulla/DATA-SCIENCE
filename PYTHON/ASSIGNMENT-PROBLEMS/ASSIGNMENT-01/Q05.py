"""
Q5. Evaluate And Print The Result of The Following Expression:
X = 10 + 3 * 2 ** 2
Based on what you learnt, And explain why the result is what it is.
"""

X = 10 + 3 * 2 ** 2
print(f"Result: {X}")

# Explanation:
# The expression is evaluated according to the order of operations (PEMDAS/BODMAS):
# 1. Exponentiation (**): 2 ** 2 = 4
# 2. Multiplication (*): 3 * 4 = 12
# 3. Addition (+): 10 + 12 = 22
