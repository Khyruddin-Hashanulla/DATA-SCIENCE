# Range Function in Python

# Example of using range() function in a for loop
for i in range(5):  # Generates numbers from 0 to 4
    print(i)

# Example of using range() with a start and end value
for i in range(1, 6):  # Generates numbers from 1 to 5
    print(i)

# Example of using range() with a step value
for i in range(0, 10, 2):  # Generates even numbers from 0 to 8
    print(i)
