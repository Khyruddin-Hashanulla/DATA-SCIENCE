# List Methods in Python

values = [7, 4, 3, 2, 9, 5]

# Append - Add one element at the end
values.append(10)
print(values)

# Insert - Insert element at index
values.insert(1, 11)
print(values)

# Sort - Arranges in increasing order
values.sort()
print(values)

# Sort(reverse = True) - Arranges in decreasing order
values.sort(reverse=True)
print(values)

# Reverse - Reverses Order
values.reverse()
print(values)
